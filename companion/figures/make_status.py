#!/usr/bin/env python3
"""Write the data behind the status map: per section of the record, how many numbered
statements there are and how many reach A8 through their own proof chain.

    python3 companion/figures/make_status.py        # from the repository root

Read from docs/results.json (generated by docs/extract.py from part_i/main.tex and
main.aux); nothing here is typed in.  Output status_part_i.dat with one row per section:
    sec  total  cond  uncond  title
"""
import json, pathlib
from collections import OrderedDict

ROOT = pathlib.Path(__file__).resolve().parents[2]
HERE = pathlib.Path(__file__).resolve().parent
results = json.loads((ROOT / "docs" / "results.json").read_text())["results"]

secs = OrderedDict()
for r in results:
    key = r["section"]["number"]
    e = secs.setdefault(key, {"title": r["section"]["title"], "total": 0, "cond": 0})
    e["total"] += 1
    e["cond"] += int(bool(r["imports_A8"]))
rows = ["sec total cond uncond title"]
for k, e in secs.items():
    rows.append("%s %d %d %d {%s}" % (k, e["total"], e["cond"], e["total"] - e["cond"], e["title"]))
(HERE / "status_part_i.dat").write_text("\n".join(rows) + "\n")
tot = sum(e["total"] for e in secs.values()); cond = sum(e["cond"] for e in secs.values())
print("sections: %d, statements: %d, reaching A8: %d" % (len(secs), tot, cond))
for k, e in secs.items():
    print("  %-3s %2d statements, %2d conditional   %s" % (k, e["total"], e["cond"], e["title"]))
