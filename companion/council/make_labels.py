#!/usr/bin/env python3
"""Write companion/council/labels.md: every number a companion may cite, from the record.

    python3 companion/council/make_labels.py        # from the repository root

Part 1 lists the 61 numbered statements from docs/results.json (itself generated from
part_i/main.tex and resolved through part_i/main.aux by docs/extract.py), with the
computed flags: whether the statement's proof chain reaches A8, and whether it cites
U_GJS by name.  Part 2 lists every other \\newlabel of part_i/main.aux -- sections,
assumptions, displayed equations -- with number and page.  Nothing here is typed in.
"""
import json, pathlib, re

ROOT = pathlib.Path(__file__).resolve().parents[2]
AUX = ROOT / "part_i" / "main.aux"
RES = ROOT / "docs" / "results.json"
OUT = pathlib.Path(__file__).resolve().parent / "labels.md"


def groups(s):
    """Split a string of concatenated {...} groups at the top level."""
    out, depth, cur = [], 0, []
    for ch in s:
        if ch == "{":
            if depth > 0:
                cur.append(ch)
            depth += 1
        elif ch == "}":
            depth -= 1
            if depth == 0:
                out.append("".join(cur))
                cur = []
            else:
                cur.append(ch)
        elif depth > 0:
            cur.append(ch)
    return out


def clean(num):
    # hyperref wraps some numbers, e.g. {{$U_{\rm GJS}$}{...}}; keep the visible text
    num = re.sub(r"\\rm\s*", "", num)
    return num.replace("{", "").replace("}", "").replace("$", "").strip()


aux = {}
for line in AUX.read_text().splitlines():
    if not line.startswith("\\newlabel{"):
        continue
    g = groups(line[len("\\newlabel"):])
    if len(g) < 2:
        continue
    label, rest = g[0], groups(g[1])
    if label.endswith("@cref"):
        continue
    number = clean(rest[0]) if rest else ""
    page = rest[1] if len(rest) > 1 else ""
    title = rest[2] if len(rest) > 2 else ""
    aux[label] = (number, page, title)

data = json.loads(RES.read_text())
results = data["results"]
by_label = {r["label"]: r for r in results}

lines = []
lines.append("# Labels and numbers of the record (`part_i/main.tex`)\n")
lines.append("Generated by `companion/council/make_labels.py` from `docs/results.json` and "
             "`part_i/main.aux`. Cite numbers from here, never from memory.\n")
n_a8 = sum(1 for r in results if r["imports_A8"])
lines.append(f"## Part 1: the {len(results)} numbered statements ({n_a8} reach A8)\n")
lines.append("| number | kind | title | label | page | section | reaches A8 | cites U_GJS | proof uses |")
lines.append("|---|---|---|---|---|---|---|---|---|")
for r in results:
    uses = ", ".join(sorted(set(r.get("proof_uses", []) + r.get("uses", []))))
    lines.append(f"| {r['number']} | {r['kind']} | {r['title']} | `{r['label']}` | {r['page']} | "
                 f"{r['section']['number']} | {'yes' if r['imports_A8'] else 'no'} | "
                 f"{'yes' if r['cites_UGJS'] else 'no'} | {uses} |")
lines.append("")
lines.append("## Part 2: every other label of `main.aux` (sections, assumptions, equations)\n")
lines.append("| label | number | page | title |")
lines.append("|---|---|---|---|")
for label, (number, page, title) in aux.items():
    if label in by_label:
        continue
    lines.append(f"| `{label}` | {number} | {page} | {title} |")
lines.append("")
lines.append(f"Counts: {len(results)} numbered statements; {len(aux)} labels in `main.aux` in total.")
OUT.write_text("\n".join(lines) + "\n")
print(f"wrote {OUT.relative_to(ROOT)}: {len(results)} statements, {len(aux)} aux labels, {n_a8} reach A8")
