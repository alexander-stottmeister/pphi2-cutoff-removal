#!/usr/bin/env python3
"""Write companion/bib.tex: the record [R], then exactly the \\bibitem entries of
part_i/main.tex that the companion cites, copied verbatim, then the record files cited by
path (PLAN.md Part 6.4, O3).

    python3 companion/make_bib.py        # from the repository root or from companion/
"""
import pathlib, re, sys

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent
main = (ROOT / "part_i" / "main.tex").read_text()
start = main.index(r"\begin{thebibliography}")
end = main.index(r"\end{thebibliography}")
body = main[start:end]
entries = {}
for m in re.finditer(r"\\bibitem\{([^}]*)\}(.*?)(?=\n\\bibitem\{|\Z)", body, re.S):
    entries[m.group(1)] = (r"\bibitem{%s}" % m.group(1)) + m.group(2).rstrip() + "\n"

cited = set()
files = sorted(HERE.glob("sections/*.tex")) + [HERE / "companion.tex"]
for f in files:
    for m in re.finditer(r"\\cite(?:\[[^\]]*\])?\{([^}]*)\}", f.read_text()):
        for k in m.group(1).split(","):
            cited.add(k.strip())
missing = sorted(k for k in cited if k not in entries)
if missing:
    sys.exit("keys not in part_i/main.tex: %s" % missing)
order = [k for k in entries if k in cited]            # the record's own order

RECORD = (r"\bibitem[R]{record}\hypertarget{bib-record}{}A.~Stottmeister, "
          r"\emph{Removal of the spatial cutoff for weakly coupled $P(\varphi)_2$: norm convergence "
          r"of the ground-state net on the quasi-local algebra. Part~I --- unified manuscript}, document of record "
          r"\texttt{part\_i/main.pdf}, 40~pp., version of 5~September 2026, "
          r"\url{https://github.com/alexander-stottmeister/pphi2-cutoff-removal}." "\n")
FILES = ["README.md", "docs/status.md", "docs/imports.md", "part_i/C5_reading_record.md",
         "part_ii/README.md", "part_ii/gate_II11_scoping.pdf", "strategy.md", "m2/m2.tex",
         "docs/figures/make_figures.py"]
out = ["% Generated by companion/make_bib.py from part_i/main.tex; do not edit by hand.",
       r"\begin{thebibliography}{99}\small", RECORD]
out += [entries[k] for k in order]
out.append(r"\end{thebibliography}")
out.append(r"\medskip\noindent{\small\raggedright\emph{Files of the record cited by path} (all in the repository above): "
           + ", ".join(r"\texttt{%s}" % f.replace("_", r"\_") for f in FILES) + r".\par}")
(HERE / "bib.tex").write_text("\n".join(out) + "\n")
print("bib.tex: [R] + %d entries (%s)" % (len(order), ", ".join(order)))
